-- Forma de pagamento na compra, CEP no endereco e estorno parcial de venda.

-- 1. Forma de pagamento da compra: o saldo do caixa passa a descontar so as compras em dinheiro.
-- Ate aqui toda compra saia do caixa, entao as antigas entram como dinheiro e o historico nao muda.
ALTER TABLE purchase ADD COLUMN payment_method character varying(30);
UPDATE purchase SET payment_method = 'DINHEIRO';
ALTER TABLE purchase ALTER COLUMN payment_method SET NOT NULL;

-- 2. CEP do endereco, so com os digitos. Os enderecos antigos ficam sem CEP: ele nunca foi gravado.
ALTER TABLE address ADD COLUMN cep character varying(8);

-- 3. Estorno parcial: a venda guarda quanto ja foi estornado, cada item guarda a quantidade devolvida
-- e cada estorno vira um registro proprio, com motivo, responsavel, valor e itens.
ALTER TABLE sale DROP CONSTRAINT sale_status_check;
ALTER TABLE sale ADD CONSTRAINT sale_status_check CHECK (status IN ('COMPLETED', 'PARTIALLY_REVERSED', 'REVERSED'));
ALTER TABLE sale ADD COLUMN reversed_amount numeric(38,2) NOT NULL DEFAULT 0;
ALTER TABLE sell_item ADD COLUMN reversed_quantity numeric(38,2) NOT NULL DEFAULT 0;

CREATE TABLE sale_reversal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id bigint NOT NULL REFERENCES sale(id),
    date timestamp(6) without time zone NOT NULL,
    reason character varying(255) NOT NULL,
    amount numeric(38,2) NOT NULL,
    user_id bigint REFERENCES app_user(id)
);

CREATE TABLE sale_reversal_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reversal_id bigint NOT NULL REFERENCES sale_reversal(id),
    sell_item_id bigint NOT NULL REFERENCES sell_item(id),
    quantity numeric(38,2) NOT NULL
);

-- Os estornos que ja existem foram sempre da venda inteira: migram para o novo formato.
INSERT INTO sale_reversal (sale_id, date, reason, amount, user_id)
SELECT id, COALESCE(reversal_date, date), COALESCE(reversal_reason, 'Não informado'), COALESCE(total, 0), reversed_by_user_id
FROM sale WHERE status = 'REVERSED';

INSERT INTO sale_reversal_item (reversal_id, sell_item_id, quantity)
SELECT r.id, i.id, i.quantity
FROM sale_reversal r JOIN sell_item i ON i.sale_id = r.sale_id;

UPDATE sell_item SET reversed_quantity = quantity
WHERE sale_id IN (SELECT id FROM sale WHERE status = 'REVERSED');

UPDATE sale SET reversed_amount = COALESCE(total, 0) WHERE status = 'REVERSED';

ALTER TABLE sale DROP COLUMN reversal_date;
ALTER TABLE sale DROP COLUMN reversal_reason;
ALTER TABLE sale DROP COLUMN reversed_by_user_id;
